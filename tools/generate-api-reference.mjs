import {readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import ts from 'typescript';

// Keep the resource indexes in sync with the public client types.
const program = ts.createProgram(['src/client.ts', 'src/scim.ts'], {
  module: ts.ModuleKind.NodeNext,
  moduleResolution: ts.ModuleResolutionKind.NodeNext,
  target: ts.ScriptTarget.ES2022,
  allowImportingTsExtensions: true,
  noEmit: true,
  skipLibCheck: true,
});
const checker = program.getTypeChecker();
const repository = 'https://github.com/2chevskii/kaiten-client/blob/master/';

for (const [file, name] of [
  ['src/client.ts', 'rest'],
  ['src/scim.ts', 'scim'],
]) {
  const source = program.getSourceFile(file);
  const client = source.statements.find(ts.isClassDeclaration);
  const type = checker.getTypeAtLocation(client);
  const resources = checker.getPropertiesOfType(type);
  for (const ru of [false, true]) {
    const prefix = ru ? 'docs/ru/reference' : 'docs/reference';
    const title = name === 'rest' ? 'REST API' : 'SCIM API';
    const intro = ru
      ? 'Методы сгруппированы по ресурсам клиента. Ссылки ведут к исходному коду с сигнатурами и типами. Дополнительные примеры и сведения о пагинации приведены в руководстве.'
      : 'Methods are grouped by client resource. Source links provide signatures and types. See the guide for examples and pagination details.';
    const guide = ru ? `/ru/guide/${name}` : `/guide/${name}`;
    const chunks = [
      `<!-- Generated by node tools/generate-api-reference.mjs. -->\n\n# ${title}\n\n${intro}\n\n[${ru ? 'Руководство' : 'Guide'}](${guide})\n`,
    ];
    for (const resource of resources) {
      const resourceType = checker.getTypeOfSymbolAtLocation(resource, client);
      const methods = checker
        .getPropertiesOfType(resourceType)
        .filter(
          method =>
            checker.getSignaturesOfType(
              checker.getTypeOfSymbolAtLocation(method, client),
              ts.SignatureKind.Call,
            ).length,
        );
      if (!methods.length) continue;
      const sourceFiles = [
        ...new Set(
          methods.map(method => {
            const declaration =
              method.valueDeclaration ?? method.declarations[0];
            return path
              .relative(process.cwd(), declaration.getSourceFile().fileName)
              .replaceAll('\\', '/');
          }),
        ),
      ];
      chunks.push(
        `## ${resource.name}\n\n${methods.map(method => `\`${method.name}\``).join(' · ')}\n\n${sourceFiles.map(sourceFile => `[${ru ? 'Исходный код' : 'Source'}](${repository}${sourceFile})`).join(' · ')}\n`,
      );
    }
    const output = `${prefix}/${name}.md`;
    const content = chunks.join('\n');
    if (process.argv.includes('--check')) {
      if ((await readFile(output, 'utf8')) !== content) {
        console.error(`${output} is out of date`);
        process.exitCode = 1;
      }
    } else {
      await writeFile(output, content);
    }
  }
}
